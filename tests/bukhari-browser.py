from playwright.sync_api import sync_playwright, expect
import os
base=os.environ.get('TEST_URL','http://127.0.0.1:8789')
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path='/usr/bin/chromium',args=['--no-sandbox'])
 page=browser.new_page(viewport={'width':1366,'height':900});errors=[]
 page.on('pageerror',lambda error:errors.append(str(error)))
 page.goto(base+'/#hadith',wait_until='networkidle')
 page.locator('.bukhari-collection-link').click()
 expect(page.locator('.bukhari-book')).to_have_count(97)
 page.locator('#bukhari-book-filter').fill('Revelation')
 expect(page.locator('.bukhari-book:visible')).to_have_count(1)
 page.locator('.bukhari-book:visible').click()
 expect(page.locator('.bukhari-entry')).to_have_count(7)
 expect(page.locator('.bukhari-ar').first).to_be_visible()
 expect(page.locator('.bukhari-en').first).to_contain_text('intentions')
 page.locator('#bukhari-language').select_option('en')
 expect(page.locator('.bukhari-ar')).to_have_count(0)
 page.locator('#bukhari-language').select_option('both')
 page.locator('#bukhari-query').fill('intentions')
 page.locator('#bukhari-search-form button').click()
 page.wait_for_url('**/#hadith/bukhari')
 page.wait_for_function('()=>document.querySelector("#bukhari-content h2")?.textContent.includes("matching entries")')
 expect(page.locator('#bukhari-content')).to_contain_text('Sahih al-Bukhari 1')
 page.locator('#bukhari-number').fill('7563')
 page.locator('#bukhari-jump-form button').click()
 expect(page.locator('.bukhari-entry')).to_have_count(1)
 expect(page.locator('.bukhari-entry h2')).to_have_text('Sahih al-Bukhari 7563')
 expect(page.locator('.bukhari-en')).to_contain_text('two words')
 page.reload(wait_until='networkidle')
 expect(page.locator('.bukhari-entry h2')).to_have_text('Sahih al-Bukhari 7563')
 page.goto(base+'/#hadith/bukhari/5710',wait_until='networkidle')
 expect(page.locator('.bukhari-entry .note')).to_contain_text('shared text')
 expect(page.locator('.bukhari-ar')).not_to_be_empty()
 page.goto(base+'/#hadith/bukhari/402.2',wait_until='networkidle')
 expect(page.locator('.bukhari-entry h2')).to_contain_text('variant 2')
 page.goto(base+'/#hadith/bukhari/book/2',wait_until='networkidle')
 expect(page.locator('.bukhari-entry')).to_have_count(20)
 page.locator('[data-bukhari-page="2"]').click()
 expect(page.locator('#bukhari-content')).to_contain_text('Page 2 of')
 page.set_viewport_size({'width':390,'height':844})
 assert page.evaluate('document.documentElement.scrollWidth<=innerWidth'), 'Mobile horizontal overflow'
 page.screenshot(path='/tmp/bukhari-mobile.png',full_page=False)
 page.goto(base+'/#route-map',wait_until='networkidle')
 expect(page.locator('.route-map-link[href^="#hadith/bukhari/book/"]')).to_have_count(97)
 # Network failure must show a retry that can recover without reloading the app.
 page.route('**/data/bukhari/book-96.json*',lambda route:route.fulfill(status=503,body='Unavailable'))
 page.goto(base+'/#hadith/bukhari/book/96',wait_until='networkidle')
 expect(page.locator('[data-bukhari-retry]')).to_be_visible()
 page.unroute('**/data/bukhari/book-96.json*')
 page.locator('[data-bukhari-retry]').click()
 expect(page.locator('.bukhari-entry')).to_have_count(20)
 assert not errors,errors
 browser.close()
 print('PASS: collection card, 97 books, Arabic/English, full search, deep links, final hadith, grouped text, variants, pagination, mobile, route map and retry.')
